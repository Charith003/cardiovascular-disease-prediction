# Import Required Libraries

import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.svm import SVC
from imblearn.over_sampling import SMOTE
import warnings
warnings.filterwarnings('ignore')

# Load and Prepare Dataset

df = pd.read_csv("cardio_train.csv", sep=';')
df.drop('id', axis=1, inplace=True)
df['age'] = (df['age'] / 365).astype(int)
df.head()

# Data Cleaning & Preprocessing

# Remove impossible values
df = df[(df['ap_hi'] >= 80) & (df['ap_hi'] <= 200)]
df = df[(df['ap_lo'] >= 50) & (df['ap_lo'] <= 130)]
df = df[df['height'] > 100]
df = df[df['weight'] < 200]
df.reset_index(drop=True, inplace=True)

# Drop ID column if present
if 'id' in df.columns:
    df.drop('id', axis=1, inplace=True)

# Convert age from days to years
df['age'] = (df['age'] / 365).astype(int)

# Check for nulls and data info
print(df.info())
print(df.isnull().sum())

# Exploratory Data Analysis (EDA)

# Plot class balance
sns.countplot(data=df, x='cardio')
plt.title("Cardiovascular Disease Distribution")
plt.show()

# Distribution plots for some features
for col in ['age', 'height', 'weight', 'ap_hi', 'ap_lo']:
    sns.histplot(df[col], kde=True)
    plt.title(f"Distribution of {col}")
    plt.show()

# Boxplots to identify outliers
for col in ['ap_hi', 'ap_lo', 'weight']:
    sns.boxplot(x=df[col])
    plt.title(f"Boxplot of {col}")
    plt.show()

# Correlation Matrix

plt.figure(figsize=(12, 6))
sns.heatmap(df.corr(), annot=True, cmap="coolwarm", fmt=".2f")
plt.title("Correlation Matrix of Features")
plt.show()

# Prepare Data for Modeling

# Features and target
X = df.drop('cardio', axis=1)
y = df['cardio']

# Handle imbalance using SMOTE
smote = SMOTE(random_state=42)
X_resampled, y_resampled = smote.fit_resample(X, y)

# Scale features
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X_resampled)

# Train-test split (complete line)
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y_resampled, test_size=0.2, random_state=42
)

# Model Evaluation Function

def evaluate_model(model, name):
    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)

    acc = accuracy_score(y_test, y_pred)

    print(f"\n{name} Accuracy: {acc:.4f}")
    print(confusion_matrix(y_test, y_pred))
    print(classification_report(y_test, y_pred))

    return acc

# Train and Compare Models

models = {
    "Logistic Regression": LogisticRegression(),
    "KNN": KNeighborsClassifier(),
    "Decision Tree": DecisionTreeClassifier(),
    "Random Forest": RandomForestClassifier(),
    "SVM": SVC()
}
accuracies = {}
for name, model in models.items():
    acc = evaluate_model(model, name)
    accuracies[name] = acc

plt.bar(accuracies.keys(), accuracies.values(), color='skyblue')
plt.xticks(rotation=45)
plt.ylabel("Accuracy")
